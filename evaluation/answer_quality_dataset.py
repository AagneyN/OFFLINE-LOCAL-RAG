"""Question sets for the end-to-end answer-quality evaluation.

Unlike evaluation_dataset.py, nothing here depends on chunk numbers, so the
sets stay valid if the chunking settings change. Each answerable question has:

  evidence  lowercase phrases that must ALL appear in the context given to
            the model (so the information needed was actually retrieved)
  answer    regular expressions that must ALL match the generated answer

DEV_SET is what changes to the pipeline are tuned against. HELDOUT_SET was
written before any tuning and is only used to confirm that an improvement
carries over to questions that were not tuned on.
"""


def answerable(question, evidence, answer):
    return {
        "question": question,
        "answerable": True,
        "evidence": evidence,
        "answer": answer,
    }


def unanswerable(question):
    return {
        "question": question,
        "answerable": False,
        "evidence": [],
        "answer": [],
    }


